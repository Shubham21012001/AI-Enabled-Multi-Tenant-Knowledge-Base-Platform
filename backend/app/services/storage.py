"""File storage abstraction: local disk in development, S3 in production.

Storage keys are generated by the server (`{org_id}/{uuid}.{ext}`) and never
contain user-supplied filenames, which rules out path traversal.
"""
import logging
import uuid
from pathlib import Path
from typing import Protocol

from app.core.config import settings

logger = logging.getLogger(__name__)


class Storage(Protocol):
    def save(self, key: str, data: bytes) -> None: ...
    def read(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...


class LocalStorage:
    def __init__(self, root: str):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        path = (self.root / key).resolve()
        # Defence in depth: keys are server-generated, but refuse anything that
        # would resolve outside the upload root.
        if not path.is_relative_to(self.root):
            raise ValueError("Invalid storage key")
        return path

    def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)

    def read(self, key: str) -> bytes:
        return self._path(key).read_bytes()

    def delete(self, key: str) -> None:
        self._path(key).unlink(missing_ok=True)


class S3Storage:
    def __init__(self, bucket: str, region: str):
        import boto3  # imported lazily: only needed in production

        self.bucket = bucket
        self.client = boto3.client("s3", region_name=region)

    def save(self, key: str, data: bytes) -> None:
        self.client.put_object(Bucket=self.bucket, Key=key, Body=data, ServerSideEncryption="AES256")

    def read(self, key: str) -> bytes:
        return self.client.get_object(Bucket=self.bucket, Key=key)["Body"].read()

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=key)


_storage: Storage | None = None


def get_storage() -> Storage:
    global _storage
    if _storage is None:
        if settings.STORAGE_BACKEND == "s3":
            _storage = S3Storage(settings.S3_BUCKET, settings.AWS_REGION)
        else:
            _storage = LocalStorage(settings.UPLOAD_DIR)
    return _storage


def make_key(org_id: uuid.UUID, ext: str) -> tuple[str, str]:
    """Returns (generated filename, storage key)."""
    filename = f"{uuid.uuid4().hex}.{ext}"
    return filename, f"{org_id}/{filename}"
